//! Bind the public compute_snap arguments to one frame and its projected query.
use super::*;

#[pyfunction(signature=(
    candidate_world,
    candidate_pixel,
    scene,
    world_to_pixel,
    threshold_px,
    project_onto_line=None,
    chain_first_point=None,
    start_point=None,
    axis_lock=None,
    shift_held=false,
    reference_edge=None,
    reference_mode=None,
    inference_angle_deg=3.0,
    screen_axis_px=None,
    is_occluded=None,
    are_occluded=None,
    face_under_cursor=false,
    edge_threshold_px=None,
    magnetic_axis_deg=None,
    acquired_edge=None,
    acquired_point=None,
    acquired_face_normal=None,
    acquired_points=None,
    recent_points=None,
    shift_lock_dir=None,
    shift_lock_color=None,
    shift_lock_ref=None,
    linear_mode="all",
    diagonal_span=false,
    work_plane_normal=None,
    radial_arm=false,
    axis_in_plane=false,
    free_3d=false,
    sticky_axis=None,
    dwell_axis_lock=false,
    hover_lock_edge=None,
    hover_lock_plane=None,
    face_crossing=None,
    face_outline=None,
    face_centers=None,
    face_context=None,
    start_edges=None
))]
pub(super) fn compute_snap<'p>(
    candidate_world: &Obj<'p>,
    candidate_pixel: &Obj<'p>,
    scene: &Obj<'p>,
    world_to_pixel: &Obj<'p>,
    threshold_px: &Obj<'p>,
    project_onto_line: Option<&Obj<'p>>,
    chain_first_point: Option<&Obj<'p>>,
    start_point: Option<&Obj<'p>>,
    axis_lock: Option<&Obj<'p>>,
    shift_held: bool,
    reference_edge: Option<&Obj<'p>>,
    reference_mode: Option<&Obj<'p>>,
    inference_angle_deg: f64,
    screen_axis_px: Option<&Obj<'p>>,
    is_occluded: Option<&Obj<'p>>,
    are_occluded: Option<&Obj<'p>>,
    face_under_cursor: bool,
    edge_threshold_px: Option<&Obj<'p>>,
    magnetic_axis_deg: Option<&Obj<'p>>,
    acquired_edge: Option<&Obj<'p>>,
    acquired_point: Option<&Obj<'p>>,
    acquired_face_normal: Option<&Obj<'p>>,
    acquired_points: Option<&Obj<'p>>,
    recent_points: Option<&Obj<'p>>,
    shift_lock_dir: Option<&Obj<'p>>,
    shift_lock_color: Option<&Obj<'p>>,
    shift_lock_ref: Option<&Obj<'p>>,
    linear_mode: &str,
    diagonal_span: bool,
    work_plane_normal: Option<&Obj<'p>>,
    radial_arm: bool,
    axis_in_plane: bool,
    free_3d: bool,
    sticky_axis: Option<&Obj<'p>>,
    dwell_axis_lock: bool,
    hover_lock_edge: Option<&Obj<'p>>,
    hover_lock_plane: Option<&Obj<'p>>,
    face_crossing: Option<&Obj<'p>>,
    face_outline: Option<&Obj<'p>>,
    face_centers: Option<&Obj<'p>>,
    face_context: Option<&Obj<'p>>,
    start_edges: Option<&Obj<'p>>,
) -> PyResult<Obj<'p>> {
    let py = scene.py();
    let query = py.import("built_core.snap_query")?.call_method1(
        "make_query",
        (scene.getattr("edges")?, world_to_pixel, candidate_pixel),
    )?;
    let options = PyDict::new(py);
    macro_rules! bind { ($($field:ident),*)=>{$(options.set_item(stringify!($field), $field)?;)*}; }
    bind!(
        candidate_world,
        candidate_pixel,
        scene,
        world_to_pixel,
        threshold_px,
        project_onto_line,
        chain_first_point,
        start_point,
        axis_lock,
        shift_held,
        reference_edge,
        reference_mode,
        inference_angle_deg,
        screen_axis_px,
        is_occluded,
        are_occluded,
        face_under_cursor,
        edge_threshold_px,
        magnetic_axis_deg,
        acquired_edge,
        acquired_point,
        acquired_face_normal,
        acquired_points,
        recent_points,
        shift_lock_dir,
        shift_lock_color,
        shift_lock_ref,
        linear_mode,
        diagonal_span,
        work_plane_normal,
        radial_arm,
        axis_in_plane,
        free_3d,
        sticky_axis,
        dwell_axis_lock,
        hover_lock_edge,
        hover_lock_plane,
        face_crossing,
        face_outline,
        face_centers,
        face_context,
        start_edges
    );
    let frame = py
        .import("built_core.snap_frame")?
        .call_method1("SnapFrame", (options, &query))?;
    py.import("built_core")?
        .call_method1("resolve_snap", (query, &frame, frame.getattr("state")?))
}
